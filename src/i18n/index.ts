const dictionaries: Record<Lang, Dict> = { en, bg };

export function translate(lang: Lang, key: string): string {
  const parts = key.split('.');
  let node: string | Dict | undefined = dictionaries[lang];
  for (const part of parts) {
    if (typeof node === 'object' && node !== null && part in node) {
      node = node[part];
    } else {
      node = undefined;
      break;
    }
  }
  if (typeof node === 'string') return node;
  // Fallback to English, then to the key itself.
  let fallback: string | Dict | undefined = dictionaries.en;
  for (const part of parts) {
    if (typeof fallback === 'object' && fallback !== null && part in fallback) {
      fallback = fallback[part];
    } else {
      fallback = undefined;
      break;
    }
  }
  return typeof fallback === 'string' ? fallback : key;
}
